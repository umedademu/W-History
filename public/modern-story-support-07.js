// 地図・年号・独立欄を省略せず、本文の該当節とともに全文へ到達できるようにする。
const referencePages={1:[126,128],2:[130,131,133],3:[135,136,139]};
export function modernReferencePages(scene,volume,index){
 const diagram=modernDiagramFor(scene);
 const linked=[...scene.plainBody.join('').matchAll(/P\.(\d+)(?:〜(\d+))?/g)].flatMap(match=>Array.from({length:Number(match[2]??match[1])-Number(match[1])+1},(_,i)=>Number(match[1])+i)).filter(page=>page>=125&&page<=139||page===95||page===107);
 const diagramPages=diagram?String(diagram.page).split('・').map(Number):[];
 return [...new Set([...(index===0&&volume.part===1?[125]:[]),...scene.sourceText.sourcePages,...linked,...diagramPages,...(referencePages[volume.part]??[])])].sort((a,b)=>a-b);
}
