function editedAnimation(sourceId,ref){
  const part=structuredClone(storyboards[sourceId][ref]);
  if(sourceId==="kosovo"&&ref===3)part.note="制度の成立過程を説明する図です。特定の戦いの当日に制度が始まったという意味ではありません。";
  if(sourceId==="tulip"&&ref===3)part.note="18世紀後半以降の変化を見通す場面です。";
  if(sourceId==="cairo"&&ref===3)part.title="ヒジャーズの服属と二大聖都の保護";
  if(sourceId==="preveza"&&ref===3)part.title="アンドレア＝ドリアの艦隊との海戦";
  if(sourceId==="lepanto"&&ref===1)part.positions={...part.positions,holyLeague:[12.5,41.9]};
  const edit=mapEdits[sourceId+":"+ref]??{};
  part.ids=[...part.ids.filter(id=>!edit.omit?.includes(id)),...edit.add??[]];
  // 取り除いた背景の地点・人物に付随する表示設定も片付ける。
  for(const key of ["positions","labels","images","icons","afterImages","afterIcons","badges"])
    if(part[key])part[key]=Object.fromEntries(Object.entries(part[key]).filter(([id])=>part.ids.includes(id)));
  for(const key of ["grow","fades"])if(part[key])part[key]=part[key].filter(id=>part.ids.includes(id));
  if(part.areas)part.areas=part.areas.filter(a=>part.ids.includes(a.id));
  if(part.capital&&!part.ids.includes(part.capital))delete part.capital;
  return {...part,sourceRef:ref,text:text[sourceId+":"+ref]};
}

