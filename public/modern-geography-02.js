const normalize = text => String(text).replace(/<rt>[\s\S]*?<\/rt>/g,'').replace(/<[^>]*>/g,'').replace(/[\s＝=・『』「」]/g,'');
const byKey = new Map(modernNameCatalog.map(entry=>[entry.key,entry]));
const escapePattern = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const pattern = new RegExp([...byKey.keys()].sort((a,b)=>b.length-a.length).map(escapePattern).join('|'),'g');
export function modernNamesInText(text) {
  const value = normalize(text);
  const found = new Map();
  for (const match of value.matchAll(pattern)) {
    const entry = byKey.get(match[0]);
    if (!found.has(entry.family)) found.set(entry.family,entry);
  }
  return [...found.values()];
}
