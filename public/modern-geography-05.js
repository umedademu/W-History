const byKey=new Map(modernNameCatalog.map(entry=>[entry.key,entry]));
const escapePattern=value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const pattern=new RegExp([...byKey.keys()].sort((a,b)=>b.length-a.length).map(key=>key==='清'?`(?<![一-龯])${escapePattern(key)}(?![一-龯])`:escapePattern(key)).join('|'),'g');
export function modernNamesInText(text) {
 const value=normalize(text).replace(/ギリシア正教徒|ギリシア正教/g,'').replace(/神聖ローマ皇帝|神聖ローマ帝国|ウィーン体制|アドリアノープル条約|ウンキャルスケレッシ条約|カルロヴィッツ条約|サンステファノ条約|ベルリン条約|パリ条約|ロンドン4国条約/g,'').replace(/英仏/g,'イギリスフランス').replace(/英露墺普/g,'イギリスロシアオーストリアプロイセン');
 const found=new Map();for(const match of value.matchAll(pattern)){const entry=byKey.get(match[0]);if(!found.has(entry.family))found.set(entry.family,entry);}if(value.includes('ポーランド反乱')&&!found.has('ポーランド'))found.set('ポーランド',byKey.get('ポーランド'));return [...found.values()];
}
