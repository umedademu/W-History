const normalize = s => s.replace(/[\s＝=・『』「」]/g,'');
export const ancientNameCatalog = catalog.map(e=>({...e,key:normalize(e.name)}));
const byKey = new Map(ancientNameCatalog.map(e=>[e.key,e]));
const pattern = new RegExp([...byKey.keys()].sort((a,b)=>b.length-a.length).map(k => {
  const escaped=k.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
  return k.length===1 ? `(?<![一-龯])${escaped}(?![一-龯])` : escaped;
}).join('|'),'g');
export function ancientNamesInText(text) {
  // 語の中の「インドラ→インド」「アッシュルバニバル→アッシュル」等を除く。
  const narrative=normalize(text).replaceAll('インドヨーロッパ語系','　　　　　　　　　');
  return [...new Map([...narrative.matchAll(pattern)].filter(m=>{
    const entry=byKey.get(m[0]), tail=narrative.slice(m.index+m[0].length);
    return !(entry.name==='インド' && /^(ラ|ヨーロッパ)/.test(tail)) && !(entry.name==='唐' && /^突/.test(tail));
  }).map(m=>[m[0],byKey.get(m[0])])).values()];
}

