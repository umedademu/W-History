export function modernDiagramFor(scene){
 if(sceneDiagrams[scene.id])return modernDiagrams[sceneDiagrams[scene.id]];
 const lines=scene.sourceText?.passages?.flatMap(passage=>passage.lines)??[];
 return modernDiagrams[lines.map(line=>lineDiagrams[line]).find(Boolean)];
}
export function modernReferencePages(scene,volume,index){
 const diagram=modernDiagramFor(scene);
 const linked=[...scene.plainBody.join('').matchAll(/P\.(\d+)/g)].map(match=>Number(match[1])).filter(page=>page>=93&&page<=107);
 const diagramPages=diagram?String(diagram.page).split('・').map(Number):[];
 return [...new Set([...(index===0&&volume.part===1?[93]:[]),...scene.sourceText.sourcePages,...linked,...diagramPages])].sort((a,b)=>a-b);
}
