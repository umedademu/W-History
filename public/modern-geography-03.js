const normalize = text => String(text ?? '').replace(/<rt\b[^>]*>[\s\S]*?<\/rt>/g,'').replace(/<[^>]*>/g,'').replace(/[\s＝=・『』「」]/g,'');
const byKey = new Map(modernNameCatalog.map(entry=>[entry.key,entry]));
const escapePattern = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const pattern = new RegExp([...byKey.keys()].sort((a,b)=>b.length-a.length).map(key=>key==='リー'?`(?<![ァ-ヿ])${escapePattern(key)}(?![ァ-ヿ])`:key==='13州'?`(?<![0-9])${escapePattern(key)}`:escapePattern(key)).join('|'),'g');
export function modernNamesInText(text) {
  let value = normalize(text);
  const found = new Map();
  // 首都と劇場の所在地の文脈だけを都市として読む。中立を宣言する大統領は人物である。
  if (/首都ワシントン|ワシントンのフォード劇場/.test(value)) {
    const city = {...byKey.get('首都ワシントン'),key:'ワシントン'};
    found.set(city.family,city);
    value=value.replace(/首都ワシントン|ワシントン(?=のフォード劇場)/g,match=>' '.repeat(match.length));
  }
  // カーネギー製鋼会社・USスティール等を個人の所在地として扱わない。
  value=value.replace(/カーネギー製鋼会社|カーネギーホール/g,match=>' '.repeat(match.length));
  for (const match of value.matchAll(pattern)) {
    let entry=byKey.get(match[0]);
    if(entry.name==='西部' && value.includes('ジャクソン'))entry={...entry,points:[[-90,38]]};
    if (!found.has(entry.family)) found.set(entry.family,entry);
  }
  // ホールは会社名と別の建物として、原文が述べた場合だけ返す。
  if(normalize(text).includes('カーネギーホール'))found.set('カーネギー・ホール',byKey.get('カーネギーホール'));
  return [...found.values()];
}
